import { NextResponse } from "next/server";
import { auth } from "@/auth";
import { prisma } from "@/lib/prisma";
import { adjustCoins, fetchBalance } from "@/lib/coins-api";
import { recordAudit } from "@/lib/audit";
import { serverFor, store, type CatalogId } from "@/lib/store";

/**
 * Buy an item with coins and queue it for in-game delivery.
 *
 *   POST { mode, itemId, idem }
 *
 * Nothing here talks to a Minecraft server. The charge is taken with an
 * idempotency key and a Purchase row is parked in `pending`; the Paper jar on
 * the item's own server polls /api/purchase/pending and runs the command as
 * console once the buyer is online there. Only `pending` rows are ever handed
 * out, so a crash between the row write and the debit cannot give anything
 * away for free.
 *
 * `idem` is generated by the browser per attempt and is what makes a retried
 * click safe: the same key always maps to the same row and the same charge.
 */

type PurchaseState =
  | { state: "signed-out" }
  | { state: "unlinked" }
  | { state: "no-discord" }
  | { state: "unknown-item" }
  | { state: "unavailable" }
  | { state: "insufficient"; price: number; balance: number }
  | { state: "ok"; server: string }
  | { state: "failed"; reason: string }
  | { state: "error" };

const IDEM_RE = /^[A-Za-z0-9_-]{8,64}$/;
const CHARGE_KEY_PREFIX = "purchase:";

function renderCommand(tpl: string, uuid: string, username: string) {
  return tpl.replace(/\{username\}/g, username).replace(/\{uuid\}/g, uuid).trim();
}

function pick(mode: string, itemId: string) {
  if (mode !== "practice" && mode !== "survival") return null;
  const ranks = store.catalog[mode as CatalogId].ranks;
  return ranks.find((i) => i.id === itemId) ?? null;
}

export async function POST(request: Request): Promise<NextResponse<PurchaseState>> {
  const session = await auth();
  const userId = (session?.user as { id?: string } | undefined)?.id;
  if (!userId) return NextResponse.json({ state: "signed-out" }, { status: 401 });

  let body: { mode?: unknown; itemId?: unknown; idem?: unknown };
  try {
    body = (await request.json()) as typeof body;
  } catch {
    return NextResponse.json({ state: "error" }, { status: 400 });
  }
  const mode = typeof body.mode === "string" ? body.mode : "";
  const itemId = typeof body.itemId === "string" ? body.itemId : "";
  const idem = typeof body.idem === "string" ? body.idem : "";
  if (!mode || !itemId || !IDEM_RE.test(idem)) {
    return NextResponse.json({ state: "error" }, { status: 400 });
  }
  if (mode !== "practice" && mode !== "survival") {
    return NextResponse.json({ state: "error" }, { status: 400 });
  }

  const item = pick(mode, itemId);
  if (!item) return NextResponse.json({ state: "unknown-item" }, { status: 404 });
  // Refuse before any coins move if the item is not live yet or has no
  // command to run (HANDOVER: never ship available: true without a grant).
  if (!item.available || !item.command.trim()) {
    return NextResponse.json({ state: "unavailable" }, { status: 409 });
  }
  const server = serverFor(mode as CatalogId);
  if (!server) return NextResponse.json({ state: "error" }, { status: 500 });

  const link = await prisma.minecraftLink.findUnique({ where: { userId } });
  if (!link?.uuid) return NextResponse.json({ state: "unlinked" }, { status: 409 });
  const username = link.username ?? link.uuid;

  const account = await prisma.account.findFirst({
    where: { userId, provider: "discord" },
  });
  if (!account?.providerAccountId) {
    return NextResponse.json({ state: "no-discord" }, { status: 409 });
  }
  const discordId = account.providerAccountId;

  const command = renderCommand(item.command, link.uuid, username);
  if (!command) return NextResponse.json({ state: "error" }, { status: 500 });

  // A retried click reuses the same idem key: finish the original purchase
  // rather than starting (and charging) a second one.
  const existing = await prisma.purchase.findUnique({ where: { idem } });
  if (existing) {
    if (existing.userId !== userId) {
      return NextResponse.json({ state: "error" }, { status: 403 });
    }
    if (existing.status !== "charging") {
      return NextResponse.json(
        existing.status === "failed"
          ? { state: "failed", reason: existing.error ?? "charge-failed" }
          : { state: "ok", server: existing.server },
      );
    }
    return charge(existing.id, discordId, item.price, item.name, idem, server);
  }

  // Balance is only ever read, never trusted: the charge below is the
  // authority, and the bot refuses an overdraft. This is a courtesy check so
  // the player gets a clear "not enough coins" instead of a bare failure.
  const balance = await fetchBalance(discordId, link.uuid);
  if (!balance.ok) {
    return NextResponse.json({ state: "error" }, { status: 502 });
  }
  if (balance.coins < item.price) {
    return NextResponse.json(
      {
        state: "insufficient",
        price: item.price,
        balance: balance.coins,
      },
      { status: 409 },
    );
  }

  let id: string;
  try {
    const row = await prisma.purchase.create({
      data: {
        idem,
        userId,
        itemId: item.id,
        mode,
        server,
        uuid: link.uuid,
        username,
        command,
        status: "charging",
      },
    });
    id = row.id;
  } catch {
    // Lost the race to a concurrent identical request — report the winner.
    const won = await prisma.purchase.findUnique({ where: { idem } });
    if (won && won.userId === userId && won.status !== "charging") {
      return NextResponse.json(
        won.status === "failed"
          ? { state: "failed", reason: won.error ?? "charge-failed" }
          : { state: "ok", server: won.server },
      );
    }
    return NextResponse.json({ state: "error" }, { status: 409 });
  }

  return charge(id, discordId, item.price, item.name, idem, server);
}

async function charge(
  id: string,
  discordId: string,
  price: number,
  name: string,
  idem: string,
  server: string,
): Promise<NextResponse<PurchaseState>> {
  const result = await adjustCoins(
    discordId,
    -price,
    `Store: ${name}`,
    CHARGE_KEY_PREFIX + idem,
  );
  if (!result.ok) {
    await prisma.purchase.update({
      where: { id },
      data: { status: "failed", error: result.reason },
    });
    return NextResponse.json({ state: "failed", reason: result.reason }, { status: 502 });
  }

  await prisma.purchase.update({ where: { id }, data: { status: "pending", error: null } });
  const row = await prisma.purchase.findUnique({ where: { id } });
  await recordAudit({
    kind: "purchase",
    source: "web",
    userId: row?.userId ?? null,
    uuid: row?.uuid ?? null,
    username: row?.username ?? null,
    meta: {
      purchaseId: id,
      itemId: row?.itemId,
      mode: row?.mode,
      server,
      price,
      discordId,
    },
  });
  return NextResponse.json({ state: "ok", server });
}
